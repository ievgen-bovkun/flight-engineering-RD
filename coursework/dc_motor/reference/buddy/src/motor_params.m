function p = motor_params()
%MOTOR_PARAMS  Параметри системи "ДПС + інерційне навантаження".
%
%   p = MOTOR_PARAMS() повертає структуру з усіма фізичними параметрами,
%   вимогами до якості керування та налаштуваннями симуляції.
%   Єдине джерело правди для всіх розділів проєкту (2.1 - 2.6).
%
%   Приклад:
%       p = motor_params();
%       m = motor_models(p);

% ---------- Електрична частина якоря ----------
p.Ra = 2.0;      % опір якоря, Ом
p.La = 0.5;      % індуктивність якоря, Гн
p.Kt = 0.1;      % стала моменту, Нм/А
p.Ke = 0.1;      % стала протиЕРС, В/(рад/с)

% ---------- Механічна частина ----------
p.Jm = 0.01;     % момент інерції ротора, кг*м^2
p.Bm = 0.001;    % коефіцієнт в'язкого тертя ротора, Нм*с/рад
p.JL = 0.02;     % момент інерції навантаження, кг*м^2

% Навантаження жорстко з'єднане з валом і додає ЛИШЕ інерцію
% (власного тертя за умовою не має), тому інерції додаються, а тертя - ні.
p.J = p.Jm + p.JL;   % сумарна інерція = 0.03 кг*м^2
p.B = p.Bm;          % сумарне тертя    = 0.001 Нм*с/рад

% ---------- Вимоги до системи керування (розділ 2.2) ----------
p.w_ref   = 100;   % цільова кутова швидкість, рад/с
p.ts_spec = 2.0;   % допустимий час перехідного процесу (смуга 2%), с
p.os_spec = 5.0;   % бажане перерегулювання, %

% ---------- Обмеження виконавчого пристрою ----------
% В умові напруга живлення не задана, тому її вибрано розрахунково
% (див. CHECK_FEASIBILITY та розділ 2.2 звіту).
%
%   * для утримання 100 рад/с у сталому режимі потрібно лише 12 В;
%   * АЛЕ для РОЗГОНУ до 100 рад/с за 2 с потрібно щонайменше 39.5 В
%     навіть за стратегії "повний газ" - це фізична межа об'єкта,
%     яку не обійти жодним регулятором;
%   * 24 В дають мінімум 3.58 с, тобто вимогу виконати НЕМОЖЛИВО.
%
% Обрано 48 В: стандартна шина живлення, ~20% запасу над теоретичним
% мінімумом плюс резерв напруги на гальмування при вході у смугу 2%.
p.Vmax =  48;     % максимальна напруга, В
p.Vmin = -48;     % мінімальна напруга, В (двополярний міст: є гальмування)

% ---------- Збурення (розділ 2.5) ----------
p.TL_step = 0.05; % амплітуда зовнішнього моменту навантаження, Нм
p.TL_time = 1.0;  % момент прикладання збурення, с

% ---------- Налаштування симуляції ----------
p.Tsim  = 5.0;    % тривалість симуляції замкненої системи, с
p.dt    = 1e-3;   % крок виводу результатів, с
p.Tsim_ol = 30.0; % тривалість симуляції розімкненої системи, с
end

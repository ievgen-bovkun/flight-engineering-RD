function C = design_compensator(p, m, p_comp, zeta, p3)
%DESIGN_COMPENSATOR  Синтез послідовного компенсатора C(s) = Kc*(s+z)/(s+p).
%
%   C = DESIGN_COMPENSATOR(p, m, p_comp, zeta, p3)
%     p_comp - полюс компенсатора (мале значення -> lag, велике -> lead)
%     zeta   - бажаний коефіцієнт демпфування домінуючої пари   (0.7)
%     p3     - третій полюс замкненої системи; за замовчуванням S/3,
%              що МАКСИМІЗУЄ добуток полюсів, а отже мінімізує статичну
%              похибку при заданому p_comp (доведення нижче)
%
%   ТОЧНЕ РОЗМІЩЕННЯ ПОЛЮСІВ
%   ------------------------
%   Об'єкт G(s) = b/(s^2+a1*s+a0), компенсатор має 3 вільні параметри
%   (Kc, z, p), замкнений поліном - 3-го порядку. Отже полюси розміщуються
%   точно, так само як ПІД у розділі 2.2:
%
%     (s+p)(s^2+a1*s+a0) + b*Kc*(s+z)
%       = s^3 + (a1+p)s^2 + (a0+a1*p+b*Kc)s + (a0*p+b*Kc*z)
%
%   Прирівнюючи до (s^2+2*zeta*wn*s+wn^2)(s+p3):
%       p  = c2 - a1           (тобто p задається вибором суми полюсів)
%       Kc = (c1 - a0 - a1*p)/b
%       z  = (c0 - a0*p)/(b*Kc)
%
%   КЛЮЧОВЕ СТРУКТУРНЕ ОБМЕЖЕННЯ
%   ----------------------------
%   Сума всіх трьох полюсів замкненої системи дорівнює -(a1 + p) і залежить
%   ЛИШЕ від полюса компенсатора. Для lag-компенсатора p за визначенням
%   мале (полюс біля початку координат), тож сума полюсів майже дорівнює
%   -a1 = -4.033, і середня дійсна частина не перевищує -1.34. Саме тому
%   lag не здатен дати ту саму швидкодію, що lead: щоб зсунути полюси
%   вліво, потрібен великий p, а це вже lead.
%
%   СТАТИЧНА ПОХИБКА
%   ----------------
%   З b*Kc*z = c0 - a0*p випливає замкнена формула:
%       ess = 1/(1 + Kdc*Kc*z/p) = a0*p/c0
%   Тобто похибка прямо пропорційна p і обернено пропорційна добутку
%   бажаних полюсів. Це й пояснює, чому lag точний, а lead - ні, і чому
%   ЖОДЕН з них не дає нуля: на відміну від ПІД, у них немає інтегратора.

if nargin < 4 || isempty(zeta), zeta = 0.7; end

b  = p.Kt/(p.La*p.J);
a1 = (p.La*p.B + p.Ra*p.J)/(p.La*p.J);
a0 = (p.Ra*p.B + p.Kt*p.Ke)/(p.La*p.J);

S = a1 + p_comp;                       % задана сума полюсів
if nargin < 5 || isempty(p3)
    p3 = S/3;                          % максимізує c0 = wn^2*p3 при цьому S
end
wn = (S - p3)/(2*zeta);
if wn <= 0
    error('design_compensator:p3', 'p3 = %.3f завеликий для суми полюсів %.3f', p3, S);
end

c2 = S;
c1 = wn^2 + 2*zeta*wn*p3;
c0 = wn^2 * p3;

Kc = (c1 - a0 - a1*p_comp)/b;
z  = (c0 - a0*p_comp)/(b*Kc);

C.Kc = Kc;  C.z = z;  C.p = p_comp;
C.zeta = zeta;  C.wn = wn;  C.p3 = p3;
C.tf = tf(Kc*[1 z], [1 p_comp]);
C.den_cl = [1, c2, c1, c0];
C.poles  = roots(C.den_cl);
C.ess    = a0*p_comp/c0;               % відносна статична похибка
C.Kdc_loop = dcgain(m.G)*Kc*z/p_comp;  % петльове підсилення на нульовій частоті
C.u0     = Kc*p.w_ref;                 % початковий керуючий сигнал (до насичення)

if z > p_comp
    C.type = 'lag';
elseif z < p_comp
    C.type = 'lead';
else
    C.type = 'gain';
end
end

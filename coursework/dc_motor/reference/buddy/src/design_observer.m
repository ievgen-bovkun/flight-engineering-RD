function obs = design_observer(p, poles)
%DESIGN_OBSERVER  Спостерігач розширеного стану для моменту навантаження.
%
%   obs = DESIGN_OBSERVER(p, poles)
%
%   ІДЕЯ
%   ----
%   Зовнішній момент TL не вимірюється, але його можна оцінити. Додаємо
%   його до вектора станів як ще одну змінну і припускаємо, що він
%   змінюється повільно порівняно з динамікою двигуна: dTL/dt = 0.
%   Для ступінчастого збурення це припущення точне всюди, крім самого
%   моменту стрибка.
%
%   Розширена модель (вимірюється лише omega):
%       d/dt [i    ]   [ -Ra/La  -Ke/La    0   ] [i   ]   [1/La]
%            [omega] = [  Kt/J   -B/J    -1/J  ] [omega] + [ 0  ] * V
%            [TL   ]   [   0       0       0   ] [TL  ]   [ 0  ]
%       y = omega
%
%   Спостерігач:  dx_hat/dt = A*x_hat + B*u + L*(omega - omega_hat)
%
%   Оцінка TL_hat далі йде у пряму компенсацію: щоб утримати швидкість
%   під моментом TL, потрібен струм TL/Kt, тобто додаткова напруга
%   Ra*TL/Kt (див. PID_OUTPUT). Регулятор перестає "доганяти" збурення
%   через інтегратор і компенсує його майже миттєво.
%
%   Полюси спостерігача беруться приблизно у 6-8 разів швидшими за полюси
%   замкненого контуру (-5, -5, -20), щоб оцінка встигала за динамікою,
%   але не надто швидкими - високі коефіцієнти L підсилюють шум датчика.

if nargin < 2 || isempty(poles), poles = [-30, -35, -40]; end

Aa = [ -p.Ra/p.La , -p.Ke/p.La ,  0     ;
        p.Kt/p.J  , -p.B /p.J  , -1/p.J ;
        0         ,  0         ,  0     ];
Ba = [ 1/p.La ; 0 ; 0 ];
Ca = [ 0 , 1 , 0 ];

% Перевірка спостережуваності: без неї задача не має розв'язку
Ob = [Ca; Ca*Aa; Ca*Aa*Aa];
r  = rank(Ob);
if r < 3
    error('design_observer:obsv', ...
          'Розширена система неспостережувана (ранг %d з 3)', r);
end

% Розміщення полюсів спостерігача через дуальну задачу
L = place(Aa', Ca', poles)';

obs.A = Aa;  obs.B = Ba;  obs.C = Ca;
obs.L = L;
obs.poles = poles;
obs.rank_obsv = r;
obs.eig_check = eig(Aa - L*Ca);

% Примітка для звіту: оскільки вимірюється ЛИШЕ швидкість, коефіцієнт
% корекції для струму виходить великим (порядку 10^3). Якщо в установці є
% датчик струму (а в Simscape-моделі розділу 2.6 він є), спостерігач стає
% значно краще обумовленим: C = [1 0; 0 1] замість [0 1 0].
obs.note = ['Вимірюється лише omega; за наявності датчика струму ' ...
            'спостерігач краще обумовлений.'];
end

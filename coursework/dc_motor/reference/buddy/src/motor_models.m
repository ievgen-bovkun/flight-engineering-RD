function m = motor_models(p)
%MOTOR_MODELS  Аналітичні моделі ДПС з навантаженням (розділ 2.1).
%
%   m = MOTOR_MODELS(p) будує дві еквівалентні форми однієї й тієї ж моделі:
%     * передавальну функцію      omega(s)/Vin(s)
%     * модель у просторі станів  x = [i; omega]
%
%   ВИВЕДЕННЯ
%   ---------
%   Закон Кірхгофа для кола якоря (протиЕРС Ke*omega діє проти джерела):
%       La*di/dt = Vin - Ra*i - Ke*omega
%   Другий закон Ньютона для обертального руху вала:
%       J*domega/dt = Kt*i - B*omega - TL
%   де J = Jm + JL, B = Bm, TL - зовнішній момент навантаження.
%
%   Перетворення Лапласа при нульових початкових умовах:
%       (La*s + Ra)*I(s) = Vin(s) - Ke*Omega(s)
%       (J*s  + B )*Omega(s) = Kt*I(s) - TL(s)
%
%   Підставляючи I(s) з першого рівняння у друге й розв'язуючи:
%       Omega(s) = [ Kt*Vin(s) - (La*s + Ra)*TL(s) ] / Delta(s)
%       Delta(s) = (La*s + Ra)*(J*s + B) + Kt*Ke
%
%   Звідси керуючий і збурюючий канали:
%       G(s)  = Omega/Vin =  Kt / Delta(s)
%       Gd(s) = Omega/TL  = -(La*s + Ra) / Delta(s)
%
%   Вхід: p - структура від MOTOR_PARAMS.

% ------------------------------------------------------------------
% 1. Передавальна функція (канал керування)
% ------------------------------------------------------------------
m.num = p.Kt;
m.den = [ p.La*p.J , ...                 % s^2
          p.La*p.B + p.Ra*p.J , ...      % s^1
          p.Ra*p.B + p.Kt*p.Ke ];        % s^0

m.G = tf(m.num, m.den);
m.G.InputName  = 'Vin';
m.G.OutputName = 'omega';

% Передавальна функція каналу збурення
m.Gd = tf(-[p.La p.Ra], m.den);
m.Gd.InputName  = 'TL';
m.Gd.OutputName = 'omega';

% ------------------------------------------------------------------
% 2. Простір станів: x = [i; omega], u = [Vin; TL], y = omega
% ------------------------------------------------------------------
m.A  = [ -p.Ra/p.La , -p.Ke/p.La ;
          p.Kt/p.J  , -p.B /p.J  ];
m.Bu = [  1/p.La ; 0      ];    % канал напруги
m.Bd = [  0      ; -1/p.J ];    % канал моменту навантаження
m.C  = [  0 , 1 ];              % вимірюємо лише кутову швидкість
m.D  = 0;

% Повна модель з двома входами (використовується у розділі 2.5)
m.sys = ss(m.A, [m.Bu m.Bd], m.C, [0 0]);
m.sys.InputName  = {'Vin','TL'};
m.sys.OutputName = {'omega'};
m.sys.StateName  = {'i','omega'};

% Модель лише за каналом керування
m.sys_u = ss(m.A, m.Bu, m.C, m.D);

% ------------------------------------------------------------------
% 3. Характеристики для звіту
% ------------------------------------------------------------------
m.poles    = pole(m.G);            % полюси розімкненої системи
m.tau      = -1 ./ m.poles;        % сталі часу, с
m.Kdc      = dcgain(m.G);          % статичний коеф. підсилення, рад/(с*В)
m.Kdc_dist = dcgain(m.Gd);         % чутливість до моменту, рад/(с*Нм)
m.V_ss     = p.w_ref / m.Kdc;      % напруга для утримання w_ref, В
end

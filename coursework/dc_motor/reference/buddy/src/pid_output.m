function [e, u, u_un, eD] = pid_output(x, Kp, Ki, Kd, Tf, opt, p) %#ok<INUSD>
%PID_OUTPUT  Вихід ПІД-регулятора для поточного вектора станів.
%
%   [e, u, u_un, eD] = PID_OUTPUT(x, Kp, Ki, Kd, Tf, opt, p)
%
%   Винесено в окремий файл, бо використовується у двох місцях:
%   SIMULATE_CLOSED_LOOP (інтегрування) та LIVE_VISUALIZATION (відображення
%   керуючого сигналу в реальному часі). Дублювати цю логіку не можна -
%   розбіжність між ними зробила б графіки недостовірними.
%
%   Вектор станів x:
%     x(1) i        струм якоря
%     x(2) omega    кутова швидкість
%     x(3) I        інтегральна складова регулятора
%     x(4) xf       стан фільтра похідної
%     x(5:7)        оцінки спостерігача [i_hat; omega_hat; TL_hat] (необов'язково)

w  = x(2);
e  = opt.w_ref - w;                  % справжня похибка (для I-складової)
eP = opt.beta *opt.w_ref - w;        % зважена похибка для P-складової
eD = opt.gamma*opt.w_ref - w;        % зважена похибка для D-складової

D = Kd*(eD - x(4))/Tf;               % відфільтрована похідна

% Компенсація оціненого моменту навантаження (розділ 2.5).
% Щоб утримати швидкість при моменті TL, потрібен додатковий струм TL/Kt,
% а для нього - додаткова напруга Ra*TL/Kt. Для 0.05 Нм це рівно 1 В.
uff = 0;
if opt.ff && numel(x) >= 7
    uff = p.Ra*x(7)/p.Kt;
end

u_un = Kp*eP + x(3) + D + uff;       % сигнал до насичення

if opt.sat
    u = min(max(u_un, opt.Vmin), opt.Vmax);
else
    u = u_un;
end
end

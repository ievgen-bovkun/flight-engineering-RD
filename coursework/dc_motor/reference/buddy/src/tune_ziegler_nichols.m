function [K, info] = tune_ziegler_nichols(p, m)
%TUNE_ZIEGLER_NICHOLS  Налаштування ПІД за методом Зіглера-Нікольса.
%
%   [K, info] = TUNE_ZIEGLER_NICHOLS(p, m) повертає K = [Kp Ki Kd].
%
%   ЧОМУ САМЕ МЕТОД КРИВОЇ РОЗГОНУ
%   ------------------------------
%   У Зіглера-Нікольса є два методи. Перший (за граничним коефіцієнтом
%   підсилення Ku) тут ПРИНЦИПОВО НЕ ПРАЦЮЄ. Характеристичний поліном
%   замкненої системи з П-регулятором:
%
%       s^2 + a1*s + (a0 + b*Kp)
%
%   Коефіцієнт при s дорівнює a1 і не залежить від Kp. За критерієм Гурвіца
%   система другого порядку стійка за будь-якого Kp > 0: незатухаючих
%   коливань не виникає, Ku = Inf, Tu не визначений. Це загальна властивість
%   об'єктів 2-го порядку без запізнення.
%
%   Тому застосовуємо другий метод - за кривою розгону (reaction curve):
%   до перехідної характеристики розімкненої системи проводиться дотична у
%   точці перегину; її перетини з віссю часу та з рівнем усталеного значення
%   дають уявне запізнення L і сталу часу T.
%
%   Таблиця ЗН для ПІД:  Kp = 1.2/(R*L),  Ti = 2L,  Td = 0.5L,
%   де R - нахил дотичної для ОДИНИЧНОГО ступінчастого входу.

t = (0:1e-4:200)';
y = step(m.G, t);                       % відгук на 1 В

dy = gradient(y, t);
[R, iInf] = max(dy);                    % точка перегину = максимум похідної
t_i = t(iInf);
y_i = y(iInf);

L = t_i - y_i/R;                        % перетин дотичної з віссю часу
Kproc = dcgain(m.G);
T = Kproc/R;                            % стала часу з нахилу дотичної

Kp = 1.2/(R*L);
Ti = 2*L;
Td = 0.5*L;

K = [Kp, Kp/Ti, Kp*Td];

info.R = R;  info.L = L;  info.T = T;  info.Kproc = Kproc;
info.t_infl = t_i;  info.y_infl = y_i;
info.Ti = Ti;  info.Td = Td;
info.Ku = Inf;                          % див. пояснення вище
info.note = 'Метод граничного підсилення незастосовний: Ku = Inf';
end
